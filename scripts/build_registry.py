#!/usr/bin/env python
"""Generate registry/policy_registry.yaml — SYNTHETIC policy data for every claim file.

    python scripts/build_registry.py

The brief's corpus has coverage-in-force ranges per policy number; this repo never did
(SEAMS.md S5). So each claim file gets one invented policy whose window contains its loss
date — with two deliberate exceptions that give the in-force check something to refuse.
Deterministic: same claim files in, same registry out.
"""

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import claim_files

OUT = Path(__file__).resolve().parent.parent / "registry" / "policy_registry.yaml"
DEFAULT_WINDOW = ("2025-10-01", "2026-09-30")
# claim number -> the window that makes its policy NOT cover the loss date
EXCEPTIONS = {
    "CLM-2026-00603": ("2025-05-01", "2026-04-30"),   # lapsed: expired 20 days before the loss
    "CLM-2026-00604": ("2026-03-01", "2027-02-28"),   # incepted 19 days AFTER the loss
}

HEADER = """\
# SYNTHETIC policy registry — generated by scripts/build_registry.py, not client data.
# One invented policy per claim file. The in-force window contains the loss date for every
# claim except the two in EXCEPTIONS (a lapsed policy and a not-yet-incepted one), so the
# check passes by construction everywhere else; see src/registry.py.
"""


def main() -> int:
    policies, seq = [], {"motor": 0, "health": 0}
    for claim_number, cf in sorted(claim_files.load_all().items()):
        seq[cf.product] += 1
        prefix = "MOT" if cf.product == "motor" else "HLT"
        start, end = EXCEPTIONS.get(claim_number, DEFAULT_WINDOW)
        if cf.product == "motor":
            limit = {"type": "IDV", "amount": 600000 if (cf.vehicle_cc or 0) <= 1500 else 900000,
                     "currency": "INR"}
        else:
            limit = {"type": "sum_insured", "amount": 500000, "currency": "INR"}
        policies.append({
            "policy_number": f"{prefix}-2025-{seq[cf.product]:04d}",
            "product": cf.product,
            "in_force_from": start, "in_force_to": end,
            "policy_limit": limit,
            "geographical_area": "India",
            "claims": [claim_number],
        })
    OUT.write_text(HEADER + yaml.safe_dump({"policies": policies}, sort_keys=False), encoding="utf-8")
    print(f"wrote {OUT} — {len(policies)} policies")
    return 0


if __name__ == "__main__":
    sys.exit(main())
