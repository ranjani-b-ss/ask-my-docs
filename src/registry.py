"""Week 12 — the policy registry and the coverage-in-force check.

SYNTHETIC. The brief's corpus includes "coverage-in-force date ranges per policy number"; this
repo never had them (SEAMS.md S5), so ``registry/policy_registry.yaml`` was generated by
``scripts/build_registry.py`` from the claim files. Consequence worth stating once, here: for
every claim whose policy was generated with a window around its own loss date, the in-force
check passes BY CONSTRUCTION. What it genuinely exercises is the plumbing, the date
comparison at its edges, and the failure path — the two deliberate exceptions (a lapsed
policy and a policy not yet incepted) are what give the check teeth.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import yaml

REGISTRY_PATH = Path(__file__).resolve().parent.parent / "registry" / "policy_registry.yaml"


@lru_cache(maxsize=1)
def _load() -> dict:
    return yaml.safe_load(REGISTRY_PATH.read_text(encoding="utf-8"))


def policy_for_claim(claim_number: str) -> dict | None:
    for policy in _load()["policies"]:
        if claim_number in policy.get("claims", []):
            return policy
    return None


def get_policy(policy_number: str) -> dict | None:
    return next((p for p in _load()["policies"] if p["policy_number"] == policy_number), None)


def check_in_force(policy_number: str, loss_date: str) -> dict:
    """Was this policy in force on ``loss_date``? Both ends of the window are inclusive.

    ISO dates compare correctly as strings. The result always carries the window it was
    checked against, so a referral can say *why* ("window ended 2026-04-30, loss 2026-05-20")
    instead of just "not in force".
    """
    policy = get_policy(policy_number)
    if policy is None:
        return {"policy_number": policy_number, "loss_date": loss_date, "in_force": False,
                "reason": f"policy number {policy_number!r} is not in the registry",
                "in_force_from": None, "in_force_to": None}
    start, end = policy["in_force_from"], policy["in_force_to"]
    if loss_date < start:
        reason = f"loss date {loss_date} is before the policy's in-force window began ({start})"
    elif loss_date > end:
        reason = f"loss date {loss_date} is after the policy's in-force window ended ({end})"
    else:
        reason = f"loss date {loss_date} falls inside the in-force window {start} to {end}"
    return {"policy_number": policy_number, "loss_date": loss_date,
            "in_force": start <= loss_date <= end, "reason": reason,
            "in_force_from": start, "in_force_to": end}
